data class RoadmapUiState(
    val loading: Boolean = true,
    val path: String? = null,
    val kb: KnowledgeBase.Data? = null,
    val roadmap: Roadmap? = null,
    val statuses: Map<String, SkillStatus> = emptyMap(),
    val generating: Boolean = false,
    val error: String? = null,
    val mode: ModeState? = null,
)

@OptIn(ExperimentalCoroutinesApi::class)
class RoadmapViewModel(private val c: AppContainer) : ViewModel() {
    private val _state = MutableStateFlow(RoadmapUiState())
    val state: StateFlow<RoadmapUiState> = _state
    private val autoGenerated = HashSet<String>()

    init {
        viewModelScope.launch {
            val kb = c.knowledgeBase.get()
            _state.update { it.copy(kb = kb) }
            c.settings.settings.map { it.profile.careerPath to it.mode }.distinctUntilChanged()
                .flatMapLatest { (path, mode) ->
                    _state.update { it.copy(mode = c.roadmaps.modeState()) }
                    if (path == null) flowOf(Triple<String?, Roadmap?, Map<String, SkillStatus>>(null, null, emptyMap()))
                    else combine(c.roadmaps.observeRoadmap(path), c.roadmaps.observeStatuses(path)) { r, st -> Triple(path, r, st) }
                        .onEach { (_, r, _) ->
                            // The study mode was switched in Settings: rebuild in the new condition.
                            val stale = r != null && ((mode == StudyMode.STATIC && r.source == "ai") || (mode == StudyMode.AI && r.source == "static"))
                            if (stale && autoGenerated.add("$path/$mode")) generate(path)
                        }
                }
                .collect { (path, roadmap, statuses) ->
                    _state.update { it.copy(loading = false, path = path, roadmap = roadmap, statuses = statuses) }
                    if (path != null && roadmap == null && autoGenerated.add(path)) generate()
                }
        }
    }

    fun generate(forPath: String? = null) {
        val path = forPath ?: _state.value.path ?: return
        if (_state.value.generating) return
        _state.update { it.copy(generating = true, error = null) }
        viewModelScope.launch {
            try {
                c.roadmaps.generate(path)
            } catch (e: Exception) {
                _state.update { it.copy(error = e.message ?: "Something went wrong") }
            } finally {
                _state.update { it.copy(generating = false, mode = c.roadmaps.modeState()) }
            }
        }
    }

    fun cycleStatus(nodeId: String) {
        val path = _state.value.path ?: return
        val next = when (_state.value.statuses[nodeId] ?: SkillStatus.NOT_STARTED) {
            SkillStatus.NOT_STARTED -> SkillStatus.LEARNING
            SkillStatus.LEARNING -> SkillStatus.DONE
            SkillStatus.DONE -> SkillStatus.NOT_STARTED
        }
        viewModelScope.launch { c.roadmaps.setStatus(path, nodeId, next) }
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun RoadmapScreen(
    container: AppContainer,
    settings: AppSettings,
    onOpenSkill: (String, String) -> Unit,
    onSwitchCareer: () -> Unit,
    onOpenSettings: () -> Unit,
) {
    val vm: RoadmapViewModel = viewModel { RoadmapViewModel(container) }
    val s by vm.state.collectAsState()
    val expandedKnown = remember { mutableStateMapOf<Int, Boolean>() }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(if (settings.profile.name.isNotBlank()) "${settings.profile.name.trim()}'s roadmap" else "Your roadmap") },
                actions = { IconButton(onClick = onOpenSettings) { Icon(Icons.Outlined.Settings, "Settings") } },
            )
        },
    ) { pad ->
        val kb = s.kb
        val roadmap = s.roadmap
        val path = s.path
        when {
            s.loading || kb == null -> LoadingState("Loading the roadmap knowledge base…", Modifier.padding(pad))
            path == null -> MessageState("No career path chosen", "Pick a career path to get your roadmap.",
                actionLabel = "Choose a career", onAction = onSwitchCareer, modifier = Modifier.padding(pad))
            roadmap == null && s.generating -> LoadingState(
                if (s.mode?.effective == StudyMode.AI) "Retrieving skills and asking the AI to sequence them…" else "Building your roadmap…",
                Modifier.padding(pad),
            )
            roadmap == null -> MessageState("Couldn't build your roadmap", s.error ?: "Please try again.",
                actionLabel = "Try again", onAction = { vm.generate() }, modifier = Modifier.padding(pad))
            else -> {
                val career = kb.career(path)
                val allItems = roadmap.stages.flatMap { it.items }
                val done = allItems.count { s.statuses[it.nodeId] == SkillStatus.DONE }
                LazyColumn(
                    Modifier.padding(pad).fillMaxWidth(),
                    contentPadding = androidx.compose.foundation.layout.PaddingValues(16.dp),
                    verticalArrangement = Arrangement.spacedBy(8.dp),
                ) {
                    item {
                        Card(colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.primaryContainer)) {
                            Column(Modifier.padding(16.dp).fillMaxWidth(), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                                Row(verticalAlignment = Alignment.CenterVertically) {
                                    Text(career?.name ?: path, style = MaterialTheme.typography.titleLarge, modifier = Modifier.weight(1f))
                                    ModeBadge(if (roadmap.source == "ai") StudyMode.AI else StudyMode.STATIC, fallback = roadmap.source == "static-fallback")
                                }
                                Text("$done of ${allItems.size} skills done", style = MaterialTheme.typography.bodyMedium)
                                LinearProgressIndicator(progress = { if (allItems.isEmpty()) 0f else done / allItems.size.toFloat() }, modifier = Modifier.fillMaxWidth())
                                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                                    OutlinedButton(onClick = { vm.generate() }, enabled = !s.generating) {
                                        Icon(Icons.Outlined.Autorenew, null, Modifier.size(18.dp)); Spacer(Modifier.width(6.dp))
                                        Text(if (s.generating) "Working…" else "Regenerate")
                                    }
                                    OutlinedButton(onClick = onSwitchCareer) {
                                        Icon(Icons.Outlined.SwapHoriz, null, Modifier.size(18.dp)); Spacer(Modifier.width(6.dp))
                                        Text("Switch career")
                                    }
                                }
                                if (s.generating) LinearProgressIndicator(Modifier.fillMaxWidth())
                            }
                        }
                    }
                    roadmap.note?.let { note -> item { NoticeBanner(note) } }
                    s.error?.let { err -> item { NoticeBanner("Last attempt failed: $err") } }

                    roadmap.stages.forEachIndexed { i, stage ->
                        val stageDone = stage.items.count { s.statuses[it.nodeId] == SkillStatus.DONE }
                        item(key = "stage-$i") {
                            Column(Modifier.padding(top = 12.dp)) {
                                Text("Stage ${i + 1} · ${stage.title}", style = MaterialTheme.typography.titleMedium)
                                if (stage.goal.isNotBlank()) Text(stage.goal, style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                                Row(verticalAlignment = Alignment.CenterVertically, modifier = Modifier.padding(top = 4.dp)) {
                                    LinearProgressIndicator(progress = { stageDone / stage.items.size.toFloat() }, modifier = Modifier.weight(1f))
                                    Spacer(Modifier.width(8.dp))
                                    Text("$stageDone/${stage.items.size}", style = MaterialTheme.typography.labelMedium)
                                }
                            }
                        }
                        val known = stage.items.filter { it.known }
                        if (known.isNotEmpty()) {
                            val open = expandedKnown[i] == true
                            item(key = "known-$i") {
                                Row(
                                    Modifier.fillMaxWidth().clickable { expandedKnown[i] = !open }.padding(vertical = 8.dp),
                                    verticalAlignment = Alignment.CenterVertically,
                                ) {
                                    Icon(Icons.Filled.CheckCircle, null, tint = MaterialTheme.colorScheme.primary)
                                    Spacer(Modifier.width(8.dp))
                                    Text("${known.size} skill${if (known.size == 1) "" else "s"} you already know", Modifier.weight(1f), style = MaterialTheme.typography.bodyMedium)
                                    Icon(if (open) Icons.Outlined.ExpandLess else Icons.Outlined.ExpandMore, if (open) "Collapse" else "Expand")
                                }
                            }
                            if (open) items(known, key = { "k-$i-${it.nodeId}" }) { item ->
                                SkillRow(kb, path, item, s.statuses[item.nodeId], onOpenSkill, vm::cycleStatus)
                            }
                        }
                        items(stage.items.filterNot { it.known }, key = { "s-$i-${it.nodeId}" }) { item ->
                            SkillRow(kb, path, item, s.statuses[item.nodeId], onOpenSkill, vm::cycleStatus)
                        }
                    }
                }
            }
        }
    }
}

@Composable
private fun SkillRow(
    kb: KnowledgeBase.Data,
    path: String,
    item: RoadmapItem,
    status: SkillStatus?,
    onOpen: (String, String) -> Unit,
    onCycle: (String) -> Unit,
) {
    val node = kb.node(path, item.nodeId) ?: return
    val st = status ?: SkillStatus.NOT_STARTED
    Card(
        onClick = { onOpen(path, item.nodeId) },
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceContainer),
        modifier = Modifier.fillMaxWidth(),
    ) {
        Row(Modifier.padding(start = 4.dp, end = 12.dp, top = 8.dp, bottom = 8.dp), verticalAlignment = Alignment.CenterVertically) {
            IconButton(onClick = { onCycle(item.nodeId) }) { StatusIcon(st) }
            Column(Modifier.weight(1f)) {
                Text(node.title, style = MaterialTheme.typography.bodyLarge, maxLines = 2, overflow = TextOverflow.Ellipsis)
                val sub = item.why.ifBlank { node.description }
                Text(sub, style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant,
                    maxLines = 2, overflow = TextOverflow.Ellipsis)
                Text(st.label, style = MaterialTheme.typography.labelSmall, color = MaterialTheme.colorScheme.primary)
            }
            Icon(Icons.AutoMirrored.Outlined.KeyboardArrowRight, "Open")
        }
    }
}

@Composable
fun StatusIcon(status: SkillStatus) {
    when (status) {
        SkillStatus.NOT_STARTED -> Icon(Icons.Outlined.RadioButtonUnchecked, "Not started — tap to mark learning")
        SkillStatus.LEARNING -> Icon(Icons.Outlined.Timelapse, "Learning — tap to mark done", tint = MaterialTheme.colorScheme.tertiary)
        SkillStatus.DONE -> Icon(Icons.Filled.CheckCircle, "Done — tap to reset", tint = MaterialTheme.colorScheme.primary)
    }
}
